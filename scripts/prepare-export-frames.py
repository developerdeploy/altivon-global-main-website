"""Extract responsive WebP frames from the supplied export film.

Usage: python scripts/prepare-export-frames.py "path/to/Timeline 1.mov"
Only sampling, resizing and encoding are applied. The source is never changed.
"""
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
import json
import shutil
import sys

import cv2
from PIL import Image

root = Path(__file__).resolve().parents[1]
source = Path(sys.argv[1]).resolve()
assert source.is_file(), "Supply an existing video file"
capture = cv2.VideoCapture(str(source))
assert capture.isOpened(), "Video cannot be decoded"
fps = capture.get(cv2.CAP_PROP_FPS)
total = int(capture.get(cv2.CAP_PROP_FRAME_COUNT))
assert fps > 0 and total > 1, "Video has no usable frames"
out = root / "public/frames/export-journey"
for variant in ("desktop", "mobile"):
    (out / variant).mkdir(parents=True, exist_ok=True)


def encode(index, pixels):
    image = Image.fromarray(cv2.cvtColor(pixels, cv2.COLOR_BGR2RGB))
    for variant, width, quality in (("desktop", 1440, 78), ("mobile", 720, 75)):
        resized = image.copy()
        resized.thumbnail((width, width), Image.Resampling.LANCZOS)
        resized.save(out / variant / f"{index:04}.webp", "WEBP", quality=quality, method=2)


index = 0
previous = None
cuts = []
with ThreadPoolExecutor(max_workers=4) as pool:
    jobs = []
    for number in range(total):
        ok, pixels = capture.read()
        assert ok, f"Video decode failed at frame {number}"
        if number % 2:
            continue
        small = cv2.resize(cv2.cvtColor(pixels, cv2.COLOR_BGR2GRAY), (80, 45))
        if previous is not None:
            score = float(cv2.absdiff(small, previous).mean())
            if score > 20:
                cuts.append({"time": round(number / fps, 3), "difference": round(score, 1)})
        previous = small
        jobs.append(pool.submit(encode, index, pixels))
        index += 1
        if len(jobs) >= 12:
            jobs.pop(0).result()
        if index % 120 == 0:
            print(f"Encoded {index} frame pairs", flush=True)
    for job in jobs:
        job.result()
capture.release()
assert len(list((out / "desktop").glob("*.webp"))) >= index
shutil.copy2(out / "desktop/0000.webp", root / "public/images/export-journey-poster.webp")
metadata = {"count": index, "fps": fps / 2, "duration": (total - 1) / fps, "width": 1440, "height": 810, "mobileWidth": 720}
(root / "src/data/exportFrames.ts").write_text(
    "// Generated by scripts/prepare-export-frames.py.\nexport const exportFrames = "
    + json.dumps(metadata, indent=2) + " as const;\n", encoding="utf-8")
review = root / "output/handoff-review"
review.mkdir(parents=True, exist_ok=True)
(review / "video-cuts.json").write_text(json.dumps(cuts, indent=2), encoding="utf-8")
print(json.dumps(metadata), flush=True)
for variant in ("desktop", "mobile"):
    size = sum(path.stat().st_size for path in (out / variant).glob("*.webp"))
    print(f"{variant}: {size / 1024 / 1024:.2f} MiB total (loaded near the current scroll position)", flush=True)
